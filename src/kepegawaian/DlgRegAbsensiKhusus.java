    public void tampil() {
        Valid.tabelKosong(tabMode);
        try {
            if (chkTglmulai.isSelected() == true) {
                ps = koneksi.prepareStatement("select rak.*, pg.nik, pg.nama, date_format(rak.tgl_mulai,'%d-%m-%Y') tglMulai, date_format(rak.tgl_berakhir,'%d-%m-%Y') tglBerakhir "
                        + "from reg_absensi_khusus rak inner join pegawai pg on pg.nik=rak.nip where "
                        + "rak.tgl_mulai between ? and ? and pg.nik LIKE ? or "
                        + "rak.tgl_mulai between ? and ? and pg.nama like ? or "
                        + "rak.tgl_mulai between ? and ? and rak.kelompok_kerja like ? or "
                        + "rak.tgl_mulai between ? and ? and rak.hari like ? or "
                        + "rak.tgl_mulai between ? and ? and rak.aktivasi_momen like ? or "
                        + "rak.tgl_mulai between ? and ? and rak.nm_gedung like ? ORDER BY waktu_simpan desc");
            } else {
                ps = koneksi.prepareStatement("select rak.*, pg.nik, pg.nama, date_format(rak.tgl_mulai,'%d-%m-%Y') tglMulai, date_format(rak.tgl_berakhir,'%d-%m-%Y') tglBerakhir "
                        + "from reg_absensi_khusus rak inner join pegawai pg on pg.nik=rak.nip where "
                        + "pg.nik LIKE ? or "
                        + "pg.nama like ? or "
                        + "rak.kelompok_kerja like ? or "
                        + "rak.hari like ? or "
                        + "rak.aktivasi_momen like ? or "
                        + "rak.nm_gedung like ? ORDER BY waktu_simpan desc");
            }

            try {
                if (chkTglmulai.isSelected() == true) {
                    ps.setString(1, Valid.SetTgl(DTPCari1.getSelectedItem() + ""));
                    ps.setString(2, Valid.SetTgl(DTPCari2.getSelectedItem() + ""));
                    ps.setString(3, "%" + TCari.getText().trim() + "%");
                    ps.setString(4, Valid.SetTgl(DTPCari1.getSelectedItem() + ""));
                    ps.setString(5, Valid.SetTgl(DTPCari2.getSelectedItem() + ""));
                    ps.setString(6, "%" + TCari.getText().trim() + "%");
                    ps.setString(7, Valid.SetTgl(DTPCari1.getSelectedItem() + ""));
                    ps.setString(8, Valid.SetTgl(DTPCari2.getSelectedItem() + ""));
                    ps.setString(9, "%" + TCari.getText().trim() + "%");
                    ps.setString(10, Valid.SetTgl(DTPCari1.getSelectedItem() + ""));
                    ps.setString(11, Valid.SetTgl(DTPCari2.getSelectedItem() + ""));
                    ps.setString(12, "%" + TCari.getText().trim() + "%");
                    ps.setString(13, Valid.SetTgl(DTPCari1.getSelectedItem() + ""));
                    ps.setString(14, Valid.SetTgl(DTPCari2.getSelectedItem() + ""));
                    ps.setString(15, "%" + TCari.getText().trim() + "%");
                    ps.setString(16, Valid.SetTgl(DTPCari1.getSelectedItem() + ""));
                    ps.setString(17, Valid.SetTgl(DTPCari2.getSelectedItem() + ""));
                    ps.setString(18, "%" + TCari.getText().trim() + "%");
                } else {
                    ps.setString(1, "%" + TCari.getText().trim() + "%");
                    ps.setString(2, "%" + TCari.getText().trim() + "%");
                    ps.setString(3, "%" + TCari.getText().trim() + "%");
                    ps.setString(4, "%" + TCari.getText().trim() + "%");
                    ps.setString(5, "%" + TCari.getText().trim() + "%");
                    ps.setString(6, "%" + TCari.getText().trim() + "%");
                }
                rs = ps.executeQuery();                
                while (rs.next()) {
                    tabMode.addRow(new String[]{                        
                        rs.getString("nik"),
                        rs.getString("nama"),
                        rs.getString("kelompok_kerja"),
                        rs.getString("hari"),
                        rs.getString("aktivasi_momen"),
                        rs.getString("nm_gedung"),
                        rs.getString("tglMulai"),
                        rs.getString("tglBerakhir"),
                        rs.getString("status_jadwal"),
                        rs.getString("tgl_mulai"),
                        rs.getString("tgl_berakhir"),
                        rs.getString("waktu_simpan")
                    });
                }
            } catch (Exception e) {
                System.out.println("tampil() : " + e);
            } finally {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            }
        } catch (SQLException e) {
            System.out.println("Notifikasi : " + e);
        }
        LCount.setText("" + tabMode.getRowCount());
    }
    
