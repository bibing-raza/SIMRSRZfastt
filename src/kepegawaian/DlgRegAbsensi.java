    private static synchronized CefApp ambilChromium() throws Exception {
        if (aplikasiChromium == null) {
            CefAppBuilder builder = new CefAppBuilder();
            builder.setInstallDir(new File(System.getProperty("user.home"), "jcef-absensi/chromium"));
            builder.addJcefArgs("--enable-media-stream");
            builder.getCefSettings().windowless_rendering_enabled = false;

            File folderProfil = new File(System.getProperty("user.home"), "jcef-absensi/profil-simrs");

            if (!folderProfil.isDirectory() && !folderProfil.mkdirs()) {
                throw new java.io.IOException("Tidak dapat membuat folder profil: " + folderProfil);
            }

            builder.getCefSettings().root_cache_path = folderProfil.getAbsolutePath();
            builder.getCefSettings().cache_path = new File(folderProfil, "cache").getAbsolutePath();
            aplikasiChromium = builder.build();
        }

        return aplikasiChromium;
    }
    
