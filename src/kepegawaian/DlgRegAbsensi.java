    public void loadURL(String url) {
        if (!SwingUtilities.isEventDispatchThread()) {
            SwingUtilities.invokeLater(() -> loadURL(url));
            return;
        }

        // Untuk tahap ini hanya izinkan registrasi lokal.
        try {
            URI alamat = URI.create(url);
            String path = alamat.normalize().getPath();

            boolean lokal = "http".equalsIgnoreCase(alamat.getScheme())
                    && "localhost".equalsIgnoreCase(alamat.getHost())
                    && (alamat.getPort() == -1 || alamat.getPort() == 80)
                    && path != null
                    && path.startsWith("/absensirz/regabsensi/");

            boolean server = "https".equalsIgnoreCase(alamat.getScheme())
                    && "192.168.0.230".equals(alamat.getHost())
                    && alamat.getPort() == 8443
                    && path != null
                    && path.startsWith("/absensi/regabsensi/");

            boolean diizinkan
                    = alamat.getUserInfo() == null && (lokal || server);

            if (!diizinkan) {
                throw new IllegalArgumentException("Alamat registrasi belum diizinkan: " + url);
            }
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
            return;
        }

        if (browserDitutup) {
            return;
        }

        urlTerakhir = url;

        if (browser != null) {
            browser.loadURL(url);
            return;
        }

        if (sedangMemuat) {
            return;
        }

        sedangMemuat = true;
        PanelContent.removeAll();
        PanelContent.add(new JLabel("Memuat registrasi absensi...", JLabel.CENTER), BorderLayout.CENTER);
        PanelContent.revalidate();
        PanelContent.repaint();

        new SwingWorker<CefApp, Void>() {
            @Override
            protected CefApp doInBackground() throws Exception {
                System.out.println("JCEF: mulai inisialisasi.");

                CefApp app = ambilChromium();

                System.out.println("JCEF: ambilChromium selesai.");
                return app;
            }

            @Override
            protected void done() {
                sedangMemuat = false;
                System.out.println("JCEF: done, browserDitutup=" + browserDitutup + ", panelTampil=" + PanelContent.isShowing());

                if (browserDitutup) {
                    return;
                }

                try {
                    CefApp app = get();
                    System.out.println("Chromium siap, mulai membuat browser.");
                    client = app.createClient();
                    browser = client.createBrowser(urlTerakhir, false, false);
                    System.out.println("Browser dibuat: " + urlTerakhir);

                    PanelContent.removeAll();
                    PanelContent.add(
                            browser.getUIComponent(),
                            BorderLayout.CENTER
                    );
                    PanelContent.revalidate();
                    PanelContent.repaint();

                } catch (Exception e) {
                    CloseScane();
                    e.printStackTrace();

                    PanelContent.removeAll();
                    PanelContent.add(new JLabel("Browser gagal dimuat.", JLabel.CENTER), BorderLayout.CENTER);
                    PanelContent.revalidate();
                    PanelContent.repaint();

                    JOptionPane.showMessageDialog(DlgRegAbsensi.this, "Gagal memuat Chromium: " + e.getMessage());
                }
            }
        }.execute();
    }

    public void CloseScane() {
        if (!SwingUtilities.isEventDispatchThread()) {
            SwingUtilities.invokeLater(this::CloseScane);
            return;
        }

        browserDitutup = true;

        if (browser != null) {
            browser.close(true);
            browser = null;
        }

        if (client != null) {
            client.dispose();
            client = null;
        }

        PanelContent.removeAll();
        PanelContent.revalidate();
        PanelContent.repaint();
    }

