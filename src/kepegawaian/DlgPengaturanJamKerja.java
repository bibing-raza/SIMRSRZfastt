    public void tampil() {
        Valid.tabelKosong(tabMode);
        try {
            ps = koneksi.prepareStatement("select *, if(jam_datang_ramadhan='00:00:00','',jam_datang_ramadhan) jamdtgrama, "
                    + "if(jam_pulang_ramadhan='00:00:00','',jam_pulang_ramadhan) jamplgrama from pengaturan_jam_kerja where "
                    + "kelompok_kerja like ? or "
                    + "hari like ? order by kelompok_kerja");
            try {
                ps.setString(1, "%" + TCari.getText().trim() + "%");
                ps.setString(2, "%" + TCari.getText().trim() + "%");
                rs = ps.executeQuery();
                while (rs.next()) {
                    tabMode.addRow(new String[]{
                        rs.getString("kelompok_kerja"),
                        rs.getString("hari"),
                        rs.getString("jam_datang_normal"),
                        rs.getString("jam_pulang_normal"),
                        rs.getString("jamdtgrama"),
                        rs.getString("jamplgrama"),                        
                        rs.getString("jam_datang_ramadhan"),
                        rs.getString("jam_pulang_ramadhan")
                    });
                }
            } catch (Exception e) {
                System.out.println("Notif : " + e);
            } finally {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            }
        } catch (SQLException e) {
            System.out.println("Notifikasi : " + e);
        }
        LCount.setText("" + tabMode.getRowCount());
    }
    
