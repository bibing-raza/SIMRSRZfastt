    private void btnBangsalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBangsalActionPerformed
        try {
            setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
            DlgBangsal bangsal = new DlgBangsal(formUtama, false);
            bangsal.emptTeks();
            bangsal.isCek();
            bangsal.awalData();
            formUtama.tampilkanDialogDiPanelUtama(bangsal);
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Gagal membuka form " + btnBangsal.getText() + ".\n" + e.getMessage());
        } finally {
            setCursor(Cursor.getDefaultCursor());
        }
    }//GEN-LAST:event_btnBangsalActionPerformed

