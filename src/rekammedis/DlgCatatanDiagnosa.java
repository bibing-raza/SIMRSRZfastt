    private void BtnGantiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnGantiActionPerformed
        if (tbDiagnosa.getSelectedRow() != -1) {
            if (TnmDiagnosa.getText().equals("")) {
                Valid.textKosong(TnmDiagnosa, "nama diagnosa");
                TnmDiagnosa.requestFocus();
            } else if (TkodeIcd.getText().equals("")) {
                Valid.textKosong(TkodeIcd, "kode icd 10");
                TkodeIcd.requestFocus();
            } else {
                Sequel.mengedit("catatan_diagnosa", "kd_catatan='" + TkdCatatan.getText() + "'",
                        "nm_diagnosa='" + TnmDiagnosa.getText() + "', kd_icd_10='" + TkodeIcd.getText() + "'");
                emptTeks();
                tampil();
            }
        } else {
            JOptionPane.showMessageDialog(null, "Silahkan pilih/klik dulu salah satu datanya pada tabel.");
            tbDiagnosa.requestFocus();
        }
}//GEN-LAST:event_BtnGantiActionPerformed

