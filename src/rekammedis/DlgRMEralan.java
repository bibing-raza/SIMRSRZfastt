    public void setData(String norw, String norm, String nmpasien,
            String status, String kdkmr, String rgrawat, String tglmsk, Date tgl) {
        
        TNoRW.setText(norw);
        TNoRM.setText(norm);
        TNmPasien.setText(nmpasien);
        nmUnit.setText(rgrawat);
        stts = status;
        kdkamar = kdkmr;
        TtglMasuk.setText(tglmsk);
        DTPtanggal.setDate(tgl);
        tombolCek(norw);

        if (kdkamar.equals("IGDK")) {
            TabRekamMedis.setSelectedIndex(0);
        } else if (kdkamar.equals("PON")) {
            TabRekamMedis.setSelectedIndex(1);
        } else if (kdkamar.equals("MAT") || kdkamar.equals("THT") || kdkamar.equals("132") || kdkamar.equals("BDM") || kdkamar.equals("BDO")
                || kdkamar.equals("BED") || kdkamar.equals("152") || kdkamar.equals("ORT")) {
            TabRekamMedis.setSelectedIndex(3);
        }
    }

