    public void tampil() {     
        Valid.tabelKosong(tabMode);
        try {
            ps = koneksi.prepareStatement("SELECT m.*, if(m.status='aktif','Aktif','Non Aktif') stts, "
                    + "date_format(m.tgl_disahkan,'%d-%m-%Y') tgl FROM master_nomor_dokumen_erm m WHERE "
                    + "m.kode_erm like ? or "
                    + "m.nomor_dokumen like ? or "
                    + "m.nm_dokumen like ? or "
                    + "m.ttd_keluarga_pasien like ? or "
                    + "m.status like ? or "
                    + "m.unit_pengguna like ? ORDER BY m.kode_erm");
            try {
                ps.setString(1, "%" + TCari.getText().trim() + "%");
                ps.setString(2, "%" + TCari.getText().trim() + "%");
                ps.setString(3, "%" + TCari.getText().trim() + "%");
                ps.setString(4, "%" + TCari.getText().trim() + "%");
                ps.setString(5, "%" + TCari.getText().trim() + "%");
                ps.setString(6, "%" + TCari.getText().trim() + "%");
                rs = ps.executeQuery();
                while (rs.next()) {
                    tabMode.addRow(new String[]{                        
                        rs.getString("kode_erm"),
                        rs.getString("nomor_dokumen"),
                        rs.getString("nm_dokumen"),
                        rs.getString("stts"),
                        rs.getString("tgl"),
                        rs.getString("ttd_keluarga_pasien"),
                        rs.getString("status"),
                        rs.getString("tgl_disahkan"),                        
                        rs.getString("waktu_simpan"),
                        rs.getString("unit_pengguna")
                    });
                }
            } catch (Exception e) {
                System.out.println("tampil() : " + e);
            } finally {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            }
        } catch (SQLException e) {
            System.out.println("Notifikasi : " + e);
        }
        LCount.setText("" + tabMode.getRowCount());
    }
    
    public void emptTeks() {  
        TkdErm.setText("");
        TnoDok.setText("");
        TnmDokumen.setText("");
        cmbStatus.setSelectedIndex(0);
        TtglDisahkan.setDate(new Date());
        cmbDokumen.setSelectedIndex(0);
        cmbUnit.setSelectedIndex(0);
        TnoDok.requestFocus();
        AutoKode();
    }

    private void getData() {
        stts = "";
        if (tbNomor.getSelectedRow() != -1) {
            TkdErm.setText(tbNomor.getValueAt(tbNomor.getSelectedRow(), 0).toString());
            TnoDok.setText(tbNomor.getValueAt(tbNomor.getSelectedRow(), 1).toString());
            TnmDokumen.setText(tbNomor.getValueAt(tbNomor.getSelectedRow(), 2).toString());
            cmbStatus.setSelectedItem(tbNomor.getValueAt(tbNomor.getSelectedRow(), 3).toString());
            cmbDokumen.setSelectedItem(tbNomor.getValueAt(tbNomor.getSelectedRow(), 5).toString());
            stts = tbNomor.getValueAt(tbNomor.getSelectedRow(), 6).toString();
            Valid.SetTgl(TtglDisahkan, tbNomor.getValueAt(tbNomor.getSelectedRow(), 7).toString());
            cmbUnit.setSelectedItem(tbNomor.getValueAt(tbNomor.getSelectedRow(), 9).toString());
        }
    }
    
    public void isForm(){
        if (ChkInput.isSelected() == true) {
            ChkInput.setVisible(false);
            PanelInput.setPreferredSize(new Dimension(WIDTH, 148));
            FormInput.setVisible(true);
            ChkInput.setVisible(true);
        } else if (ChkInput.isSelected() == false) {
            ChkInput.setVisible(false);
            PanelInput.setPreferredSize(new Dimension(WIDTH, 20));
            FormInput.setVisible(false);
            ChkInput.setVisible(true);
        }
    }
    
