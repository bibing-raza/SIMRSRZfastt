    private void BtnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnSimpanActionPerformed
        if (TkdErm.getText().trim().equals("")) {
            Valid.textKosong(TkdErm, "Kode e-RM");
        } else if (TnoDok.getText().trim().equals("")) {
            Valid.textKosong(TnoDok, "No. Dokumen");
            TnoDok.requestFocus();
        } else if (TnmDokumen.getText().trim().equals("")) {
            Valid.textKosong(TnmDokumen, "Nama Dokumen");
            TnmDokumen.requestFocus();
        } else {
            AutoKode();
            
            if (cmbStatus.getSelectedIndex() == 0) {
                stts = "aktif";
            } else {
                stts = "non aktif";
            }
            
            Sequel.menyimpan("master_nomor_dokumen_erm", "'" + TkdErm.getText() + "','" + TnoDok.getText() + "',"
                    + "'" + TnmDokumen.getText() + "','" + stts + "','" + Valid.SetTgl(TtglDisahkan.getSelectedItem() + "") + "',"
                    + "'" + cmbDokumen.getSelectedItem().toString() + "','" + Sequel.cariIsi("select now()") + "',"
                    + "'" + cmbUnit.getSelectedItem().toString() + "'", "Dokumen RM");
            
            emptTeks();
            BtnCariActionPerformed(null);
        }
}//GEN-LAST:event_BtnSimpanActionPerformed

