    private void BtnTesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnTesActionPerformed
        if (Tquery.getText().equals("")) {
            JOptionPane.showMessageDialog(rootPane, "Query Sql yang dieksekusi masih kosong..!!");
            Tquery.requestFocus();
        } else {
            try {
                ps = koneksi.prepareStatement(Tquery.getText());
                try {
                    rs = ps.executeQuery();
                    if (rs.next()) {
                        JOptionPane.showMessageDialog(null, "Query Sql yang diterapkan sudah benar..!!");
                    } else {
                        JOptionPane.showMessageDialog(null, "Query Sql yang diterapkan masih salah, periksa lagi penulisanya..!!");
                    }
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(null, "Query Sql yang diterapkan masih salah, periksa lagi penulisanya berikut erornya : \n" + e);
                    System.out.println("Error Query Sql Salah : " + e);
                } finally {
                    if (rs != null) {
                        rs.close();
                    }

                    if (ps != null) {
                        ps.close();
                    }
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Query Sql yang diterapkan masih salah, periksa lagi penulisanya berikut erornya : \n" + e);
                System.out.println("Error Query Sql Salah : " + e);
            }
        }
}//GEN-LAST:event_BtnTesActionPerformed

