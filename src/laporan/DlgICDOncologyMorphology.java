    private void BtnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnSimpanActionPerformed
        if (TkodeMor.getText().trim().equals("")) {
            Valid.textKosong(TkodeMor, "Kode Morphology");
            TkodeMor.requestFocus();
        } else if (TkodeHis.getText().trim().equals("")) {
            Valid.textKosong(TkodeHis, "Kode Histology");
            TkodeHis.requestFocus();
        } else if (TnamaMor.getText().trim().equals("")) {
            Valid.textKosong(TnamaMor, "Nama Morphology");
            TnamaMor.requestFocus();
        } else if (TnamaBeha.getText().trim().equals("")) {
            Valid.textKosong(TnamaBeha, "Nama Behavior");
            TnamaBeha.requestFocus();
        } else {
            Sequel.menyimpan("master_icdo_morphology", "?,?,?,?,?,?", "Kode Morphology", 6, new String[]{
                TkodeMor.getText(), TkodeHis.getText(), cmbBeha.getSelectedItem().toString(), TnamaMor.getText(), 
                TnamaBeha.getText(), cmbStatus.getSelectedItem().toString()
            });
            
            tampil();
            emptTeks();
        }
}//GEN-LAST:event_BtnSimpanActionPerformed

