    private void tampil() {
        Valid.tabelKosong(tabMode);
        try {
            ps = koneksi.prepareStatement("select * from master_icdo_morphology WHERE "
                    + "kd_morphology LIKE ? or "
                    + "kd_histology LIKE ? or "
                    + "behavior LIKE ? or "
                    + "nm_morphology LIKE ? or "
                    + "nm_behavior LIKE ? or "
                    + "aktif LIKE ? ORDER BY kd_morphology");
            try {
                ps.setString(1, "%" + TCari.getText() + "%");
                ps.setString(2, "%" + TCari.getText() + "%");
                ps.setString(3, "%" + TCari.getText() + "%");
                ps.setString(4, "%" + TCari.getText() + "%");
                ps.setString(5, "%" + TCari.getText() + "%");
                ps.setString(6, "%" + TCari.getText() + "%");
                rs = ps.executeQuery();
                while (rs.next()) {
                    tabMode.addRow(new String[]{
                        rs.getString("kd_morphology"),
                        rs.getString("kd_histology"),
                        rs.getString("behavior"),
                        rs.getString("nm_morphology"),
                        rs.getString("nm_behavior"),
                        rs.getString("aktif")
                    });
                }
            } catch (Exception e) {
                System.out.println("tampil() : " + e);
            } finally {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            }
        } catch (Exception e) {
            System.out.println("Notifikasi : " + e);
        }
        LCount.setText("" + tabMode.getRowCount());
    }

